const dictionaries: Record<AdminUiLanguage, Dict> = { uz, cyr, ru, en };

let current: AdminUiLanguage = "uz";

export function adminLanguage(): AdminUiLanguage {
  return current;
}

export function initAdminLanguage(): AdminUiLanguage {
  let stored: string | null = null;
  try {
    stored = localStorage.getItem(ADMIN_LANGUAGE_KEY);
  } catch {
    stored = null;
  }
  current = (["uz", "cyr", "ru", "en"] as const).includes(stored as AdminUiLanguage)
    ? (stored as AdminUiLanguage)
    : "uz";
  document.documentElement.lang =
    current === "cyr" ? "uz-Cyrl" : current === "ru" ? "ru" : current === "en" ? "en" : "uz-Latn";
  return current;
}

export function setAdminLanguage(language: AdminUiLanguage): void {
  current = language;
  document.documentElement.lang =
    language === "cyr" ? "uz-Cyrl" : language === "ru" ? "ru" : language === "en" ? "en" : "uz-Latn";
  try {
    localStorage.setItem(ADMIN_LANGUAGE_KEY, language);
  } catch {
    /* storage unavailable */
  }
}

export function tt(key: string): string {
  return dictionaries[current][key] ?? dictionaries.uz[key] ?? key;
}

export function ttTemplate(key: string, values: Record<string, string | number>): string {
  let text = tt(key);
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export { dictionaries as adminDictionaries };
